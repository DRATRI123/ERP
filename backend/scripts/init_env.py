"""Create backend/.env for running on this computer, with freshly generated secrets.

Used by setup.bat / setup.sh. Never overwrites an existing .env (that would make encrypted
credentials and backups unreadable). Run: python scripts/init_env.py
"""

from __future__ import annotations

import base64
import contextlib
import os
import secrets
import sys
from pathlib import Path

from cryptography.fernet import Fernet

ENV = Path(__file__).resolve().parents[1] / ".env"


def main() -> int:
    if ENV.exists():
        print(f"{ENV} already exists — keeping it.")
        return 0
    ENV.write_text(f"""# Local settings for this computer — generated by scripts/init_env.py. Keep this file private.
# Losing it means losing the keys below: back it up together with your data.
ERP_ENV=development
ERP_SECRET_KEY={secrets.token_urlsafe(64)}
ERP_DATABASE_URL=sqlite:///./data/erp.db
# Credentials of connected services are encrypted with this key.
ERP_ENCRYPTION_KEYS=["{Fernet.generate_key().decode()}"]
# Backups are encrypted with this key. Copy it somewhere safe (password manager).
ERP_BACKUP_KEY={base64.urlsafe_b64encode(os.urandom(32)).decode()}
ERP_BACKUP_DIR=./data/backups
# The web app keeps the session in a secure cookie.
ERP_AUTH_COOKIE=true
ERP_PUBLIC_BASE_URL=http://localhost:3000
ERP_TIMEZONE=Asia/Kolkata
# Optional: Redis for live updates (ERP_REDIS_URL=redis://localhost:6379/0)
""", encoding="utf-8")
    with contextlib.suppress(OSError):  # not supported on every filesystem (e.g. Windows)
        os.chmod(ENV, 0o600)
    print(f"Created {ENV} with new secret keys.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
